const setLanguage = (language) => {
  const lang = aboutCopy[language] ? language : 'en';
  const copy = aboutCopy[lang];
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (value) element.textContent = value;
  });
  const switcher = document.querySelector('.about-language');
  switcher?.classList.toggle('is-fr', lang === 'fr');
  document.querySelectorAll('[data-lang]').forEach((button) => button.setAttribute('aria-pressed', String(button.dataset.lang === lang)));
  const presenceHeading = document.querySelector('[data-presence-transition] h2');
  if (presenceHeading) presenceHeading.setAttribute('aria-label', [...presenceHeading.querySelectorAll('span')].map((word) => word.textContent.trim()).join(' '));
  try {
    localStorage.setItem('space-language', lang);
    localStorage.removeItem('spaceLanguage');
  } catch {}
  window.dispatchEvent(new CustomEvent('space:language', { detail: { language: lang } }));
};

document.querySelectorAll('[data-lang]').forEach((button) => button.addEventListener('click', () => setLanguage(button.dataset.lang)));

const observer = 'IntersectionObserver' in window ? new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (!entry.isIntersecting) return;
    entry.target.classList.add('is-visible');
    observer.unobserve(entry.target);
  });
}, { threshold: .13, rootMargin: '0px 0px -6% 0px' }) : null;

document.querySelectorAll('.reveal').forEach((element, index) => {
  if (index === 0 || !observer) element.classList.add('is-visible');
  else observer.observe(element);
});

const presenceTransition = document.querySelector('[data-presence-transition]');
if (presenceTransition) {
  const words = [...presenceTransition.querySelectorAll('h2 span')];
  if ('IntersectionObserver' in window) {
    const wordObserver = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add('is-word-visible');
      });
    }, { threshold: .35, rootMargin: '-12% 0px -32% 0px' });
    const sectionObserver = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) words.forEach((word) => word.classList.remove('is-word-visible'));
      });
    }, { threshold: 0 });
    words.forEach((word) => wordObserver.observe(word));
    sectionObserver.observe(presenceTransition);
  } else {
    words.forEach((word) => word.classList.add('is-word-visible'));
  }
}

/*
 * The perfume collage is tied directly to native scroll progress. Nothing here
 * cancels wheel events or changes the document scroll position, so the page
 * stays fluid while the frames assemble into the final composition.
 */
const collageSection = document.querySelector('.about-collage');
const collageGallery = collageSection?.querySelector('.about-cover-gallery');
const collageFrames = collageGallery ? [...collageGallery.querySelectorAll('.cover-image')] : [];
const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)');
const compactMotion = window.matchMedia('(max-width: 900px), (pointer: coarse)');

if (collageSection && collageGallery && collageFrames.length && (reducedMotion.matches || compactMotion.matches)) {
  collageFrames.forEach((frame) => {
    frame.style.setProperty('--reveal-x', '0px');
    frame.style.setProperty('--reveal-y', '0px');
    frame.style.setProperty('--reveal-scale', '1');
    frame.style.setProperty('--reveal-opacity', '1');
  });
  collageGallery.classList.add('is-scroll-ready');
} else if (collageSection && collageGallery && collageFrames.length) {
  const entrances = [
    [-34, -48], [12, 54], [38, -44], [-30, 46], [34, 50],
    [-20, -42], [42, -24], [-38, 22], [18, 48], [-42, -18],
    [10, 50], [34, -42], [-32, 38], [42, 20], [-12, 46]
  ];
  let animationFrame = 0;

  const renderCollage = () => {
    animationFrame = 0;
    const viewportHeight = window.innerHeight || 1;
    const bounds = collageSection.getBoundingClientRect();
    const travel = Math.max(1, collageSection.offsetHeight - viewportHeight);
    const progress = Math.min(1, Math.max(0, -bounds.top / travel));
    const step = .56 / Math.max(1, collageFrames.length - 1);
    const duration = .22;

    collageFrames.forEach((frame, index) => {
      const start = (index - 4) * step;
      const local = Math.min(1, Math.max(0, (progress - start) / duration));
      const eased = 1 - Math.pow(1 - local, 3);
      const [fromX, fromY] = entrances[index % entrances.length];
      frame.style.setProperty('--reveal-x', `${(fromX * (1 - eased)).toFixed(2)}px`);
      frame.style.setProperty('--reveal-y', `${(fromY * (1 - eased)).toFixed(2)}px`);
      frame.style.setProperty('--reveal-scale', (.92 + eased * .08).toFixed(4));
      frame.style.setProperty('--reveal-opacity', (.06 + eased * .94).toFixed(4));
    });

    collageGallery.classList.add('is-scroll-ready');
  };

  const requestCollageRender = () => {
    if (animationFrame) return;
    animationFrame = window.requestAnimationFrame(renderCollage);
  };

  renderCollage();
  window.addEventListener('scroll', requestCollageRender, { passive: true });
  window.addEventListener('resize', requestCollageRender, { passive: true });
  window.addEventListener('pageshow', requestCollageRender);
}

const companyTimeline = document.querySelector('[data-company-timeline]');
if (companyTimeline) {
  const timelineList = companyTimeline.querySelector('[data-timeline-list]');
  const timelineItems = [...companyTimeline.querySelectorAll('[data-timeline-item]')];
  if (reducedMotion.matches || compactMotion.matches || !('IntersectionObserver' in window)) {
    timelineItems.forEach((item) => item.classList.add('is-visible'));
    timelineList?.style.setProperty('--timeline-progress', '1');
  } else {
    const timelineObserver = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add('is-visible');
        timelineObserver.unobserve(entry.target);
      });
    }, { threshold: .28, rootMargin: '0px 0px -12% 0px' });
    timelineItems.forEach((item) => timelineObserver.observe(item));
    let timelineFrame = 0;
    const renderTimeline = () => {
      timelineFrame = 0;
      const bounds = timelineList.getBoundingClientRect();
      const start = window.innerHeight * .76;
      const travel = Math.max(1, bounds.height + window.innerHeight * .22);
      const progress = Math.min(1, Math.max(0, (start - bounds.top) / travel));
      timelineList.style.setProperty('--timeline-progress', progress.toFixed(4));
    };
    const requestTimelineRender = () => {
      if (!timelineFrame) timelineFrame = window.requestAnimationFrame(renderTimeline);
    };
    renderTimeline();
    window.addEventListener('scroll', requestTimelineRender, { passive: true });
    window.addEventListener('resize', requestTimelineRender, { passive: true });
  }
}

